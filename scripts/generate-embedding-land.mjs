import { writeFile } from "node:fs/promises";
import {
  landDetailPoints,
  landPoints,
} from "../src/demos/embeddings/land-data.ts";

const POSITION_SCALE = 32_767;

function encodePoints(points) {
  const bytes = new Uint8Array(
    points.length * 3 * Int16Array.BYTES_PER_ELEMENT,
  );
  const view = new DataView(bytes.buffer);
  let offset = 0;
  for (const point of points) {
    for (const coordinate of point) {
      view.setInt16(offset, Math.round(coordinate * POSITION_SCALE), true);
      offset += Int16Array.BYTES_PER_ELEMENT;
    }
  }

  let binary = "";
  const chunkSize = 0x8000;
  for (let index = 0; index < bytes.length; index += chunkSize) {
    binary += String.fromCharCode(...bytes.subarray(index, index + chunkSize));
  }
  return btoa(binary);
}

function sourceConstant(name, points) {
  const base64 = encodePoints(points);
  const chunks = base64.match(/.{1,100}/g) ?? [];
  return `const ${name} = [\n${chunks
    .map((chunk) => `  "${chunk}",`)
    .join("\n")}\n].join("");`;
}

const base = landPoints(1);
const detail = landDetailPoints(1);
const output = `// Generated by deno task generate:embedding-land. Do not edit by hand.
const POSITION_SCALE = 32_767;

function decodePoints(encoded: string): Float32Array {
  const binary = atob(encoded);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index++) {
    bytes[index] = binary.charCodeAt(index);
  }
  const quantized = new Int16Array(bytes.buffer);
  return Float32Array.from(quantized, (coordinate) => coordinate / POSITION_SCALE);
}

${sourceConstant("BASE_POINTS", base)}
${sourceConstant("DETAIL_POINTS", detail)}

export const LAND_POINT_POSITIONS = decodePoints(BASE_POINTS);
export const LAND_DETAIL_POSITIONS = decodePoints(DETAIL_POINTS);
`;

await writeFile(
  new URL("../src/demos/embeddings/land-points.generated.ts", import.meta.url),
  output,
);
console.log(
  `Generated ${base.length} base points and ${detail.length} detail points.`,
);
